#!/usr/bin/env python3
"""Convert Fonts/*.otf → public/fonts/exhibition/*.woff2 (+ ExhibitionBlank).

Large CFF sources are subroutinized so browser-decoded SFNT stays ~2MB, not 14–21MB.
"""
from __future__ import annotations

from pathlib import Path

import cffsubr
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "Fonts"
EXHIBITION = ROOT / "public" / "fonts" / "exhibition"

# Source filename in Fonts/ → public id (matches exhibition-fonts.ts)
SOURCE_MAP: dict[str, str] = {
    "OneAndAQuarter_edited.otf": "ilgwasa",
    "nori-Regular.otf": "nori",
    "mangul-Regular.otf": "mangul",
    "Bunhaeneung_Regular.otf": "gamtu",
    "Hapum-Regular.otf": "yawp",
    "허당_박혜원-Regular.otf": "heodang",
    "Eoseureum-Regular_edited.otf": "eoseureum",
    "doldol-Regular.otf": "doldol",
    "dragonfly-Regular.otf": "jamjari",
    "ulmeok-Regular.otf": "ulmeok",
    "GuGu-Regular.otf": "bidul",
    "Byeokjomok-Regular.otf": "byeokjomok",
    "Haetsal_Regular.otf": "haetsal",
    "Seonyu-Regular.otf": "seonyu",
    "popcorn-Regular.otf": "popcorn",
    "seopung-Regular.otf": "seopung",
    "seopung-Medium.otf": "seopung-medium",
}


def empty_glyph():
    return TTGlyphPen(None).glyph()


def cmap_to_unicode_range(cmap: dict[int, str]) -> str:
    if not cmap:
        return "U+0-0"
    parts: list[str] = []
    start = prev = None
    for cp in sorted(cmap):
        if start is None:
            start = prev = cp
            continue
        if cp == prev + 1:
            prev = cp
            continue
        parts.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
        start = prev = cp
    if start is not None:
        parts.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
    return ", ".join(parts)


def write_unicode_ranges_ts(ranges: dict[str, str]) -> None:
    out = ROOT / "src" / "lib" / "exhibition-font-unicode-ranges.generated.ts"
    lines = [
        "/** Generated by scripts/convert-fonts-woff2.py — do not edit. */",
        "export const EXHIBITION_FACE_UNICODE_RANGES: Record<string, string> = {",
    ]
    for key in sorted(ranges):
        lines.append(f"  {key!r}: {ranges[key]!r},")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


def collect_face_unicode_ranges() -> dict[str, str]:
    ranges: dict[str, str] = {}
    for woff2 in sorted(EXHIBITION.glob("*.woff2")):
        if woff2.name == "ExhibitionBlank.woff2":
            continue
        font = TTFont(woff2)
        cmap = font.getBestCmap() or {}
        font.close()
        ranges[woff2.name] = cmap_to_unicode_range(cmap)
    return ranges


def build_blank_woff2(out: Path) -> None:
    fb = FontBuilder(1000, isTTF=True)
    names = [".notdef", "blank"]
    fb.setupGlyphOrder(names)
    blank = empty_glyph()
    # Browsers (OTS) reject a font whose glyf table is entirely empty, so .notdef gets a
    # 1-unit contour. Mapped codepoints use the empty "blank" glyph, so nothing is drawn.
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0))
    pen.lineTo((0, 1))
    pen.lineTo((1, 0))
    pen.closePath()
    fb.setupGlyf({".notdef": pen.glyph(), "blank": blank})
    metrics = {n: (500, 0) for n in names}
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    # cmap format 13 (many-to-one): every codepoint below maps to the one empty glyph, so
    # no character can fall through to a system font. (Format 4/12 cannot express this
    # without >65k glyphs.) Surrogates and C0/C1 controls are left unmapped.
    from fontTools.ttLib import newTable
    from fontTools.ttLib.tables._c_m_a_p import CmapSubtable

    cmap: dict[int, str] = {}
    for start, end in ((0x20, 0x7E), (0xA0, 0xD7FF), (0xE000, 0x10FFFF)):
        for cp in range(start, end + 1):
            cmap[cp] = "blank"
    sub = CmapSubtable.newSubtable(13)
    sub.platformID, sub.platEncID, sub.language, sub.cmap = 3, 10, 0, cmap
    cmap_table = newTable("cmap")
    cmap_table.tableVersion = 0
    cmap_table.tables = [sub]
    fb.font["cmap"] = cmap_table
    fb.setupNameTable(
        {
            "familyName": "ExhibitionBlank",
            "styleName": "Regular",
            "uniqueFontIdentifier": "ExhibitionBlank-Regular",
            "fullName": "ExhibitionBlank Regular",
            "psName": "ExhibitionBlank-Regular",
            "version": "Version 1.000",
        }
    )
    fb.setupOS2(sTypoAscender=800, usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    font = fb.font
    font.flavor = "woff2"
    out.parent.mkdir(parents=True, exist_ok=True)
    font.save(out)
    print(f"wrote {out.name} ({out.stat().st_size} bytes)")


def convert_otf(src: Path, dst: Path) -> None:
    font = TTFont(src, recalcBBoxes=False, recalcTimestamp=False)
    cff_before = len(font.getTableData("CFF ")) if "CFF " in font else 0
    if "CFF " in font and cff_before > 1_500_000:
        cffsubr.subroutinize(font)
        cff_after = len(font.getTableData("CFF "))
        print(f"  subroutinize CFF {cff_before:,} → {cff_after:,}")
    font.flavor = "woff2"
    dst.parent.mkdir(parents=True, exist_ok=True)
    font.save(dst)
    font.close()
    print(f"{src.name} → {dst.name} ({src.stat().st_size:,} → {dst.stat().st_size:,})")


def main() -> None:
    EXHIBITION.mkdir(parents=True, exist_ok=True)
    build_blank_woff2(EXHIBITION / "ExhibitionBlank.woff2")

    for src_name, out_id in SOURCE_MAP.items():
        src = SRC_DIR / src_name
        if not src.exists():
            print(f"skip missing {src_name}")
            continue
        convert_otf(src, EXHIBITION / f"{out_id}.woff2")

    # Remove stale otf in exhibition dir if any
    for otf in EXHIBITION.glob("*.otf"):
        otf.unlink()
        print(f"removed {otf.name}")

    write_unicode_ranges_ts(collect_face_unicode_ranges())


if __name__ == "__main__":
    main()
